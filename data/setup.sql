USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS LAB_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS DAY0_LAB;
CREATE SCHEMA IF NOT EXISTS DAY0_LAB.HEALTHCARE;
USE WAREHOUSE LAB_WH;
USE SCHEMA DAY0_LAB.HEALTHCARE;

CREATE STAGE IF NOT EXISTS LAB_DATA
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  DIRECTORY = (ENABLE = TRUE);
CREATE FILE FORMAT IF NOT EXISTS LAB_CSV
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"';

CREATE TABLE IF NOT EXISTS PATIENTS (
  PATIENT_ID VARCHAR, FIRST_NAME VARCHAR, LAST_NAME VARCHAR, BIRTHDATE DATE,
  GENDER VARCHAR, RACE VARCHAR, CITY VARCHAR, COUNTY VARCHAR, STATE VARCHAR,
  INCOME NUMBER(10,0), PAYER VARCHAR, PRIMARY_CONDITION VARCHAR
);
CREATE TABLE IF NOT EXISTS ENCOUNTERS (
  ENCOUNTER_ID VARCHAR, PATIENT_ID VARCHAR, START_TS TIMESTAMP_NTZ, STOP_TS TIMESTAMP_NTZ,
  ENCOUNTER_CLASS VARCHAR, DESCRIPTION VARCHAR, TOTAL_COST NUMBER(12,2), PAYER_COVERAGE NUMBER(12,2)
);
CREATE TABLE IF NOT EXISTS CLINICAL_NOTES (
  NOTE_ID VARCHAR, PATIENT_ID VARCHAR, ENCOUNTER_ID VARCHAR,
  NOTE_DATE DATE, NOTE_TYPE VARCHAR, NOTE_TEXT VARCHAR
);
SHOW TABLES IN SCHEMA DAY0_LAB.HEALTHCARE;
