"""Generate the continuous developer-style guide from canonical index.html content."""
import json
from dataclasses import dataclass
from html import escape
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VOID_TAGS = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input',
             'link', 'meta', 'param', 'source', 'track', 'wbr'}


@dataclass
class Module:
    identifier: str
    title: str
    minutes: int
    optional: bool
    body: str


class GuideSource(HTMLParser):
    """Preserve raw module markup, changing only its heading levels."""

    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.modules = []
        self.metadata = []
        self.logo = []
        self.current = None
        self.parts = []
        self.stack = []
        self.in_metadata = False
        self.in_logo = False

    @staticmethod
    def heading(tag):
        return f'h{int(tag[1]) + 1}' if tag in ('h1', 'h2', 'h3', 'h4', 'h5') else tag

    def emit(self, markup):
        if self.current is not None:
            self.parts.append(markup)
        if self.in_logo:
            self.logo.append(markup)

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        if tag == 'script' and attributes.get('id') == 'snowflake-report-metadata':
            self.in_metadata = True
        if tag == 'section' and 'step' in attributes.get('class', '').split():
            if self.current is not None:
                raise ValueError('Nested lab modules are not supported')
            self.current = attributes
            self.parts = []
            return
        if self.current is None:
            return
        if tag == 'svg' and attributes.get('class') == 'coco-icon' and not self.logo:
            self.in_logo = True
        markup = self.get_starttag_text()
        mapped = self.heading(tag)
        if mapped != tag:
            markup = '<' + mapped + markup[len(tag) + 1:]
        self.emit(markup)
        if tag not in VOID_TAGS:
            self.stack.append(tag)

    def handle_startendtag(self, tag, attrs):
        self.emit(self.get_starttag_text())

    def handle_endtag(self, tag):
        if tag == 'script':
            self.in_metadata = False
        if self.current is None:
            return
        if tag == 'section':
            if self.stack:
                raise ValueError(f'Unclosed elements in {self.current["id"]}: {self.stack}')
            self.modules.append(Module(
                self.current['id'], self.current['data-title'],
                int(self.current['data-mins']), self.current.get('data-optional') == 'true',
                ''.join(self.parts),
            ))
            self.current = None
            return
        if not self.stack or self.stack.pop() != tag:
            raise ValueError(f'Unbalanced module markup at </{tag}>')
        self.emit(f'</{self.heading(tag)}>')
        if tag == 'svg':
            self.in_logo = False

    def handle_data(self, text):
        self.emit(text)
        if self.in_metadata:
            self.metadata.append(text)

    def handle_entityref(self, name):
        self.emit(f'&{name};')

    def handle_charref(self, name):
        self.emit(f'&#{name};')

    def handle_comment(self, text):
        self.emit(f'<!--{text}-->')


def render_guide(source):
    parser = GuideSource()
    parser.feed(source)
    parser.close()
    if parser.current is not None or not parser.modules or not parser.logo:
        raise ValueError('Incomplete lab source or missing CoCo logo')
    modules = sorted(parser.modules, key=lambda module: module.optional)
    core_minutes = sum(module.minutes for module in modules if not module.optional)
    metadata = json.loads(''.join(parser.metadata))
    metadata['intent'] = 'Developer-style continuous edition of the Snowflake Foundations lab'
    metadata['dataSources'].append({'type': 'file', 'path': 'index.html'})
    metadata['layoutNotes'] = (
        'Generated by tools/build_guide.py from index.html. Same instructional content and CoCo SVGs; '
        'module headings demoted one level, optional modules ordered after core wrap-up. '
        'Design inspired by https://www.snowflake.com/en/developers/guides/ai-powered-video-publishing/. '
        'Local CSS/JS only. No Snowflake execution or external runtime dependencies.'
    )
    metadata['sections'] = [{'id': module.identifier} for module in modules]
    metadata_json = json.dumps(metadata, indent=2, ensure_ascii=True).replace('<', '\\u003c')
    sections = []
    links = []
    for number, module in enumerate(modules, 1):
        identifier = escape(module.identifier, quote=True)
        title = escape(module.title, quote=True)
        track = 'Optional extension' if module.optional else 'Core module'
        optional = ' data-optional="true"' if module.optional else ''
        sections.append(
            f'<section class="step" id="{identifier}" data-title="{title}" '
            f'data-mins="{module.minutes}" data-module="{number:02d}" '
            f'data-track="{track}"{optional}>{module.body}</section>'
        )
        if module.optional and (number == 1 or not modules[number - 2].optional):
            links.append('<li class="toc-divider">Optional extensions</li>')
        links.append(
            f'<li><a href="#{identifier}"><span class="toc-number" aria-hidden="true">{number:02d}</span>'
            f'<span>{title}</span><span class="toc-time">{module.minutes} min</span></a></li>'
        )
    template = (ROOT / 'tools/guide-template.html').read_text()
    values = {
        'METADATA': metadata_json,
        'LOGO': ''.join(parser.logo),
        'CORE_MINUTES': str(core_minutes),
        'CONTENTS': '\n'.join(links),
        'MODULES': '\n\n'.join(sections),
    }
    for key, value in values.items():
        template = template.replace('{{' + key + '}}', value)
    return template


def build_guide():
    target = ROOT / 'guide.html'
    target.write_text(render_guide((ROOT / 'index.html').read_text()))
    return target


if __name__ == '__main__':
    print(f'Generated {build_guide().name} from index.html.')